#!/usr/bin/env python3
"""Derive a PPU-host copy of a causal SC-GRPO config by remapping gpu006 absolute paths.

  python ppu_make_config.py <src_tag> <dst_tag> [key=value ...]

Reads examples/embodiment/config/libero_safety_scgrpo_causal_<src_tag>.yaml and writes
libero_safety_scgrpo_causal_<dst_tag>.yaml next to it. Only paths change, plus any explicit
dotted overrides (e.g. env.train.total_num_envs=16, or +env.train.new_key=1 to add a key that the source lacks);
hyperparameters are left as in the source.
Fails if a gpu006 path remains or a remapped path does not exist on this host.
"""
import os
import pathlib
import re
import sys

R = os.environ.get("CWS_ROOT", "/mnt/cpfs/jieduan")
D, M = f"{R}/data", f"{R}/models"
WORK = os.environ.get("CWS_WORK", f"{R}/work/scgrpo")
CFG = pathlib.Path(__file__).resolve().parents[4] / "examples/embodiment/config"

# Longest prefixes first.
PATH_MAP = [
    ("/data_cf/wan_ac_sft/runs/s3_dual_b10/ema-step-41000.safetensors", f"{D}/wan_dual_41000/ema-step-41000.safetensors"),
    ("/mnt/nfs/fjj/wan_ac_sft/ckpt/RLinf-Wan-LIBERO-Spatial/Wan2.2_VAE.pth", f"{M}/wan_vae/Wan2.2_VAE.pth"),
    ("/data_cf/cws_sam/v1/scgrpo/keyframes_v1", f"{D}/scgrpo_bundle/keyframes_v1"),
    ("/data_cf/cws_sam/v1/scgrpo/channel_mask.json", f"{D}/scgrpo_bundle/scoring/channel_mask.json"),
    ("/data_cf/cws_sam/v1/checkpoints/cost_all_d32/best.pt", f"{D}/scgrpo_bundle/scoring/sam_cost_all_d32/best.pt"),
    ("/data_cf/cws_sam/v1/scgrpo/state_reg_v1/state_reg.pt", f"{D}/scgrpo_bundle/scoring/state_reg_v1/state_reg.pt"),
    ("/data_cf/cws_rm/runs/rm_v3_agent_w41k/best.pt", f"{D}/scgrpo_bundle/scoring/rm_v3_agent_w41k/best.pt"),
    ("/data_cf/cws_sam/v1/scgrpo/rm2/ra/best.pt", f"{D}/scgrpo_bundle/scgrpo_rm2_20261102/rm_models/R-A_resnet_rm2/best.pt"),
    ("/mnt/nfs/fjj/Code/rlinf-safety-runtime/checkpoints/pi05_libero_safety_rlinf", f"{M}/pi05_libero_safety_rlinf"),
    ("/data_cf/cws_sam/v1/scgrpo/", f"{WORK}/"),
]
EPISODES = f"{D}/labels/episodes.jsonl"


def set_key(text, dotted, value):
    """Replace the scalar at a dotted YAML path, matching by indentation (configs are 2-space)."""
    lines, parts, depth, start = text.split("\n"), dotted.split("."), 0, 0
    for i in range(len(lines)):
        if i < start:
            continue
        m = re.match(rf"^({'  ' * depth}){re.escape(parts[depth])}:(\s*)(.*)$", lines[i])
        if not m:
            continue
        if depth == len(parts) - 1:
            comment = re.search(r"\s+#.*$", m.group(3))
            lines[i] = f"{m.group(1)}{parts[depth]}: {value}{comment.group(0) if comment else ''}"
            return "\n".join(lines)
        depth, start = depth + 1, i + 1
    raise KeyError(dotted)


def add_key(text, dotted, value):
    """Insert a new scalar ``leaf: value`` as the first child of the existing block at the dotted parent path."""
    *parents, leaf = dotted.split(".")
    lines, depth, start = text.split("\n"), 0, 0
    for i in range(len(lines)):
        if i < start or depth == len(parents):
            continue
        if re.match(rf"^{'  ' * depth}{re.escape(parents[depth])}:\s*(#.*)?$", lines[i]):
            depth, start = depth + 1, i + 1
            if depth == len(parents):
                lines.insert(i + 1, f"{'  ' * depth}{leaf}: {value}")
                return "\n".join(lines)
    raise KeyError(dotted)


def main():
    src, dst, overrides = sys.argv[1], sys.argv[2], sys.argv[3:]
    text = (CFG / f"libero_safety_scgrpo_causal_{src}.yaml").read_text()
    for old, new in PATH_MAP:
        text = text.replace(old, new)
    text = text.replace(f"causal/{src}\"", f"causal/{dst}\"").replace(f"scgrpo_causal_{src}\"", f"scgrpo_causal_{dst}\"")
    if "episodes_jsonl:" not in text:
        text = re.sub(r"(\n    sync_real: True)", rf"\n    episodes_jsonl: {EPISODES}\1", text, count=1)
    for kv in overrides:  # key=value replaces an existing scalar; +key=value adds a new one
        k, v = kv.split("=", 1)
        text = add_key(text, k[1:], v) if k.startswith("+") else set_key(text, k, v)
    text = f"# PPU host copy of causal_{src} (generated by ppu_make_config.py; paths remapped)\n" + text
    left = re.findall(r"/(?:data_cf|mnt/nfs|NAS)/\S+", text)
    if left:
        sys.exit(f"unmapped gpu006 paths: {left}")
    for p in re.findall(rf"{re.escape(R)}/(?:data|models)/\S+", text):
        if not pathlib.Path(p.strip('"').rstrip(").,;")).exists():  # paths also appear inside comments
            sys.exit(f"missing on this host: {p}")
    out = CFG / f"libero_safety_scgrpo_causal_{dst}.yaml"
    out.write_text(text)
    print(out)


if __name__ == "__main__":
    main()
